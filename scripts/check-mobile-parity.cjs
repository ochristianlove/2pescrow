const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
const { plainTerms, tradePermissions, tradeActivity } = require('../apps/mobile/src/tradePresentation.ts');
const { translate, catalogs, languageOptions } = require('../packages/shared/src/i18n/catalog.ts');
const { french } = require('../packages/shared/src/i18n/fr.ts');
const { frenchExtra } = require('../packages/shared/src/i18n/fr-extra.ts');
const trade = { id:'sample', title:'Sample', status:'Funded', tokenSymbol:'USDT', amountAtomic:'25000000', tradeCode:'SAMPLE', contractAddress:'0xsample', buyerUserId:'buyer', sellerUserId:'seller' };
assert.equal(tradePermissions(trade, 'viewer').canPost, false);
assert.equal(tradePermissions(trade).canPost, false);
assert.equal(tradePermissions(trade, 'buyer').canConfirm, false);
assert.equal(tradePermissions(trade, 'seller').canConfirm, true);
assert.equal(tradePermissions({...trade, status:'Disputed'}, 'seller').canConfirm, false);
assert.equal(tradePermissions({...trade, tradeCode:null}, 'seller').canPost, false);
assert.equal(tradePermissions({...trade, partyRole:'admin', status:'Disputed', disputes:[{id:'case',status:'open'}]}, 'staff').canPost, true);
assert.equal(tradePermissions({...trade, partyRole:'admin', status:'Disputed', disputes:[{id:'case',status:'resolved'}]}, 'staff').canPost, false);
const timeline = tradeActivity({...trade, events:[{id:'a',eventName:'Funded',createdAt:'2026-01-01T08:00:00Z'},{id:'b',eventName:'DeadlineReminder:delivery',createdAt:'2026-01-02T08:00:00Z'}], messages:[{id:'a',kind:'user',body:'Thanks',createdAt:'2026-01-01T09:00:00Z'}]});
assert.deepEqual(timeline.map(item=>item.key), ['event:a','message:a']);
assert.equal(plainTerms('<p>Camera &amp; lens</p><ul><li>Insured delivery</li></ul><script>bad()</script>'), 'Camera & lens\n• Insured delivery');
assert.equal(plainTerms('A < B &amp; C'), 'A < B & C');
assert.equal(translate('fr','Start a trade'), 'Créer une transaction');
assert.equal(translate('fr','AwaitingFunding'), 'En attente du dépôt');
assert.equal(translate('fr',' Awaiting Funding '), ' En attente du dépôt ');
assert.equal(translate('fr','A unique user message'), 'A unique user message');
assert(languageOptions.some(option=>option.id==='fr'));
const keys = new Set(catalogs.flatMap(catalog=>Object.values(catalog).flatMap(Object.keys)));
const missingFrench = [...keys].filter(key=> !Object.hasOwn(french,key) && !Object.hasOwn(frenchExtra,key));
assert.deepEqual(missingFrench, []);
console.log(`Trade permissions, history, terms, and French catalog checks passed (${keys.size} existing catalog keys).`);
